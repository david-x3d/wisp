#!/usr/bin/env python3
"""Generates the Wisp logo (SVG) and the Android adaptive icon layers.

The mark is a soft 9-sided "cookie" (a Material 3 Expressive shape) holding a
small voice waveform: two dots and three rounded bars. Run from the repo root:

    python3 scripts/make_logo.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"

VIOLET = "#6A4CFF"
MAGENTA = "#C04DE8"
CORAL = "#FF7E8B"
CREAM = "#FFF7F2"
INK = "#2A1C66"


def cookie_path(cx, cy, r, lobes=9, depth=0.075, steps=216):
    """Closed path of a rounded cookie: r(t) = r * (1 + depth * cos(lobes * t))."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps - math.pi / 2
        rr = r * (1 + depth * math.cos(lobes * (t + math.pi / 2)))
        pts.append((cx + rr * math.cos(t), cy + rr * math.sin(t)))
    d = f"M{pts[0][0]:.2f},{pts[0][1]:.2f}"
    d += "".join(f"L{x:.2f},{y:.2f}" for x, y in pts[1:])
    return d + "Z"


def pill(cx, cy, w, h):
    """Vertical capsule centred on (cx, cy)."""
    r = w / 2
    top, bottom = cy - h / 2 + r, cy + h / 2 - r
    return (
        f"M{cx - r:.2f},{top:.2f}"
        f"A{r:.2f},{r:.2f} 0 0 1 {cx + r:.2f},{top:.2f}"
        f"L{cx + r:.2f},{bottom:.2f}"
        f"A{r:.2f},{r:.2f} 0 0 1 {cx - r:.2f},{bottom:.2f}Z"
    )


def wave(cx, cy, size):
    """Two dots and three bars: a short spoken phrase. Returns path data."""
    w = size * 0.13
    gap = size * 0.19
    heights = [0.115, 0.30, 0.52, 0.30, 0.115]
    parts = []
    for i, hf in enumerate(heights):
        x = cx + (i - 2) * gap
        parts.append(pill(x, cy, w, max(size * hf, w)))
    return "".join(parts)


def svg_logo(size=512):
    c = size / 2
    r = size * 0.44
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{VIOLET}"/>
      <stop offset="0.55" stop-color="{MAGENTA}"/>
      <stop offset="1" stop-color="{CORAL}"/>
    </linearGradient>
    <radialGradient id="shine" cx="0.32" cy="0.26" r="0.7">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.28"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <path d="{cookie_path(c, c, r)}" fill="url(#g)"/>
  <path d="{cookie_path(c, c, r)}" fill="url(#shine)"/>
  <path d="{wave(c, c, size * 0.62)}" fill="{CREAM}"/>
</svg>
"""


def svg_mono(size=512):
    c = size / 2
    r = size * 0.44
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">
  <path fill-rule="evenodd" d="{cookie_path(c, c, r)}{wave(c, c, size * 0.62)}" fill="#000000"/>
</svg>
"""


def vector(paths, viewport=108, size_dp=108):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_logo.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}
</vector>
"""


def gradient_fill(x1, y1, x2, y2):
    return f"""        <aapt:attr name="android:fillColor">
            <gradient android:type="linear"
                android:startX="{x1}" android:startY="{y1}"
                android:endX="{x2}" android:endY="{y2}">
                <item android:offset="0" android:color="#FF{VIOLET[1:]}"/>
                <item android:offset="0.55" android:color="#FF{MAGENTA[1:]}"/>
                <item android:offset="1" android:color="#FF{CORAL[1:]}"/>
            </gradient>
        </aapt:attr>"""


def main():
    (ROOT / "branding").mkdir(exist_ok=True)
    (ROOT / "branding/logo.svg").write_text(svg_logo())
    (ROOT / "branding/logo-mono.svg").write_text(svg_mono())

    # Adaptive icon: 108x108 canvas, 66dp safe circle in the middle.
    bg = vector([
        '    <path android:pathData="M0,0h108v108h-108z">',
        gradient_fill(0, 0, 108, 108),
        "    </path>",
        f'    <path android:fillColor="#33FFFFFF" android:pathData="{cookie_path(40, 34, 30, 9, 0.0)}"/>',
    ])
    fg = vector([
        f'    <path android:fillColor="#1F000000" android:pathData="{cookie_path(54, 55.4, 31)}"/>',
        f'    <path android:fillColor="#FF{CREAM[1:]}" android:pathData="{cookie_path(54, 54, 31)}"/>',
        '    <path android:pathData="' + wave(54, 54, 40) + '">',
        gradient_fill(34, 34, 74, 74),
        "    </path>",
    ])
    mono = vector([
        f'    <path android:fillColor="#FF000000" android:fillType="evenOdd" android:pathData="{cookie_path(54, 54, 31)}{wave(54, 54, 40)}"/>',
    ])
    # Brand mark for use inside the app (full colour, square, no padding).
    mark = vector([
        f'    <path android:pathData="{cookie_path(24, 24, 22)}">',
        gradient_fill(0, 0, 48, 48),
        "    </path>",
        f'    <path android:fillColor="#FF{CREAM[1:]}" android:pathData="{wave(24, 24, 29)}"/>',
    ], viewport=48, size_dp=48)
    # Status bar / notification glyph: white, cut-out waveform.
    stat = vector([
        f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{cookie_path(12, 12, 11)}{wave(12, 12, 14.5)}"/>',
    ], viewport=24, size_dp=24)

    RES.mkdir(parents=True, exist_ok=True)
    (RES / "ic_launcher_background.xml").write_text(bg)
    (RES / "ic_launcher_foreground.xml").write_text(fg)
    (RES / "ic_launcher_monochrome.xml").write_text(mono)
    (RES / "ic_wisp_mark.xml").write_text(mark)
    (RES / "ic_stat_wisp.xml").write_text(stat)
    print("logo + icon layers written")


if __name__ == "__main__":
    main()
